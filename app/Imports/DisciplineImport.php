<?php

namespace App\Imports;

use App\Models\Discipline;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;
use Maatwebsite\Excel\Concerns\ToCollection;
use Maatwebsite\Excel\Concerns\WithValidation;
use Maatwebsite\Excel\Concerns\Importable;
use Maatwebsite\Excel\Concerns\WithStartRow;

class DisciplineImport implements ToCollection, WithValidation, WithStartRow
{
    use Importable;

    protected $clubId;
    protected $importedCount = 0;
    protected $errors = [];
    protected $validatedData = []; // Store all validated data before import

    public function __construct($clubId)
    {
        $this->clubId = $clubId;
    }

    /**
     * Bắt đầu lấy dữ liệu từ dòng số 5 (A5) - đây là dòng dữ liệu đầu tiên
     * Row 1: Title, Row 2: Instructions, Row 3: Empty, Row 4: Headers, Row 5+: Data
     */
    public function startRow(): int
    {
        return 5;
    }

    /**
     * Map row data by column position since we're not using WithHeadingRow
     * Column A (0): Tên, Column B (1): Điểm, Column C (2): Mô tả
     */
    private function mapRowData($row)
    {
        $rowArray = $row->toArray();

        // Logging removed

        return [
            'ten_ky_luat' => $rowArray[0] ?? '',      // Column A: Tên
            'diem' => $rowArray[1] ?? '',     // Column B: Điểm
            'mo_ta' => $rowArray[2] ?? ''     // Column C: Mô tả
        ];
    }

    /**
     * @param Collection $collection
     */
    public function collection(Collection $collection)
    {
        // Step 1: Validate all data first before any import operation
        $this->validateAllData($collection);

        // Step 2: If there are validation errors, stop the import process
        if (!empty($this->errors)) {
            return; // Don't import anything if there are validation errors
        }

        // Step 3: If all data is valid, perform the import within a database transaction
        DB::beginTransaction();

        try {
            foreach ($this->validatedData as $validData) {
                // Create discipline record
                Discipline::create([
                    'club_id' => $this->clubId,
                    'name' => $validData['name'],
                    'discipline_points' => $validData['points'],
                    'description' => $validData['description'],
                    'status' => 'active'
                    // code will be auto-generated by the model
                ]);

                $this->importedCount++;
            }

            // If we reach here, all imports were successful
            DB::commit();
        } catch (\Exception $e) {
            // If any error occurs during import, rollback all changes
            DB::rollback();
            $this->errors[] = "Lỗi trong quá trình import: " . $e->getMessage();
            $this->importedCount = 0;
        }
    }

    /**
     * Validation rules for each row - using column positions (0, 1, 2)
     */
    public function rules(): array
    {
        return [
            '0' => 'nullable|string|max:255',  // Column A: Tên kỷ luật
            '1' => 'nullable',                 // Column B: Điểm
            '2' => 'nullable|string'           // Column C: Mô tả
        ];
    }

    /**
     * Custom validation messages
     */
    public function customValidationMessages()
    {
        return [
            '0.string' => 'Tên kỷ luật phải là chuỗi ký tự.',
            '0.max' => 'Tên kỷ luật không được vượt quá 255 ký tự.',
            '1.numeric' => 'Điểm kỷ luật phải là số nguyên.',
            '2.string' => 'Mô tả phải là chuỗi ký tự.'
        ];
    }

    /**
     * Get number of imported records
     */
    public function getImportedCount()
    {
        return $this->importedCount;
    }

    /**
     * Get import errors
     */
    public function getErrors()
    {
        return $this->errors;
    }

    /**
     * Validate all data before performing any import operations
     * This ensures that if there are any validation errors, no data will be imported
     */
    private function validateAllData(Collection $collection)
    {
        $this->validatedData = [];
        $this->errors = [];
        $existingNames = []; // Track names within this import to prevent duplicates

        foreach ($collection as $index => $row) {
            $rowNumber = $index + 5; // Actual Excel row number (starting from row 5 for data)

            try {
                // Map the row data by column position
                $mappedRow = $this->mapRowData($row);

                // Skip completely empty rows
                if (empty(trim($mappedRow['ten_ky_luat'])) && empty(trim($mappedRow['diem'])) && empty(trim($mappedRow['mo_ta']))) {
                    continue;
                }

                // Validate required fields manually for better error messages
                if (empty(trim($mappedRow['ten_ky_luat'] ?? ''))) {
                    $this->errors[] = "Dòng {$rowNumber}: Tên kỷ luật không được để trống.";
                    continue;
                }

                if (empty(trim($mappedRow['diem'])) && $mappedRow['diem'] !== 0 && $mappedRow['diem'] !== '0') {
                    $this->errors[] = "Dòng {$rowNumber}: Điểm kỷ luật không được để trống.";
                    continue;
                }

                // Validate points is numeric
                if (!is_numeric($mappedRow['diem'])) {
                    $this->errors[] = "Dòng {$rowNumber}: Điểm kỷ luật phải là số nguyên.";
                    continue;
                }

                $name = trim($mappedRow['ten_ky_luat']);
                $points = (int) $mappedRow['diem'];
                $description = trim($mappedRow['mo_ta'] ?? '');

                // Check for duplicate names within this import file
                $nameKey = strtolower($name);
                if (in_array($nameKey, $existingNames)) {
                    $this->errors[] = "Dòng {$rowNumber}: Tên kỷ luật '{$name}' đã tồn tại trong file import này.";
                    continue;
                }

                // Check for duplicate names in database for this club
                $existingDiscipline = Discipline::where('club_id', $this->clubId)
                    ->where('name', 'LIKE', $name)
                    ->first();

                if ($existingDiscipline) {
                    $this->errors[] = "Dòng {$rowNumber}: Tên kỷ luật '{$name}' đã tồn tại trong câu lạc bộ này.";
                    continue;
                }

                // Add to existing names tracking
                $existingNames[] = $nameKey;

                // Store validated data for later processing
                $this->validatedData[] = [
                    'name' => $name,
                    'points' => $points,
                    'description' => $description,
                    'row_number' => $rowNumber
                ];
            } catch (\Exception $e) {
                $this->errors[] = "Dòng {$rowNumber}: Lỗi không xác định - " . $e->getMessage();
            }
        }
    }
}
